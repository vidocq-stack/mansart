package io.vidocq.mansart.data.tests;

import io.vidocq.mansart.data.core.MansartData;
import io.vidocq.mansart.data.core.PathResolver;
import io.vidocq.mansart.data.core.RepositoryRuntime;
import io.vidocq.mansart.data.dialect.Attribute;
import io.vidocq.mansart.data.dialect.Dialect;
import io.vidocq.mansart.data.dialect.OrderBy;
import io.vidocq.mansart.data.dialect.Where;
import io.vidocq.mansart.data.dialect.h2.H2Dialect;
import io.vidocq.mansart.data.dialect.postgresql.PostgresqlDialect;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.MethodSource;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.time.LocalDate;
import java.util.List;
import java.util.stream.Stream;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * Every predicate shape of the dialect-neutral {@link Where} tree — case-insensitive and scalar-function forms of each
 * comparator, negations, joins along a relation path — rendered by the H2 and the PostgreSQL dialects and run on H2
 * (in PostgreSQL mode for the PostgreSQL dialect).
 */
class DialectPredicatesTest {

    private static final String ALPHA = "Alpha";
    private static final String BRAVO = "Bravo";
    private static final String CHARLIE = "Charlie";

    static Stream<Arguments> dialects() {
        return Stream.of(
                Arguments.of("H2", new H2Dialect(), "jdbc:h2:mem:mansart-predicates-h2;DB_CLOSE_DELAY=-1"),
                Arguments.of("PostgreSQL", new PostgresqlDialect(),
                        "jdbc:h2:mem:mansart-predicates-pg;MODE=PostgreSQL;DB_CLOSE_DELAY=-1"));
    }

    private static RepositoryRuntime runtime(Dialect dialect, String url) throws SQLException {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL(url);
        ds.setUser("sa");
        try (Connection c = ds.getConnection(); Statement s = c.createStatement()) {
            s.execute("DROP TABLE IF EXISTS \"books\"");
            s.execute("DROP TABLE IF EXISTS \"authors\"");
            s.execute("CREATE TABLE \"authors\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "\"name\" VARCHAR(200) NOT NULL)");
            s.execute("CREATE TABLE \"books\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "\"title\" VARCHAR(300) NOT NULL, \"author_id\" BIGINT NOT NULL, \"published_on\" DATE, "
                    + "\"version\" INT)");
            s.execute("INSERT INTO \"authors\" (\"name\") VALUES ('Alpha'), ('Bravo'), ('Charlie')");
            s.execute("INSERT INTO \"books\" (\"title\", \"author_id\", \"published_on\", \"version\") "
                    + "VALUES ('First', 1, DATE '2020-01-01', 0), ('Second', 2, NULL, 0)");
        }
        return MansartData.builder().dataSource(ds).dialect(dialect).build().runtime();
    }

    private static List<String> names(RepositoryRuntime rt, Where where, Object... args) {
        return rt.queryList(_Author.$MODEL, where, new OrderBy(List.of(OrderBy.Order.asc(_Author.name))), args)
                .stream().map(Author::getName).toList();
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("dialects")
    void rendersCaseInsensitiveComparisons(String name, Dialect dialect, String url) throws SQLException {
        RepositoryRuntime rt = runtime(dialect, url);
        Attribute<?, ?> n = _Author.name;

        assertThat(names(rt, new Where.IgnoreCase(new Where.NotEq(n)), "alpha")).containsExactly(BRAVO, CHARLIE);
        assertThat(names(rt, new Where.IgnoreCase(new Where.Like(n)), "%RAV%")).containsExactly(BRAVO);
        assertThat(names(rt, new Where.IgnoreCase(new Where.Lt(n)), "bravo")).containsExactly(ALPHA);
        assertThat(names(rt, new Where.IgnoreCase(new Where.Lte(n)), "bravo")).containsExactly(ALPHA, BRAVO);
        assertThat(names(rt, new Where.IgnoreCase(new Where.Gt(n)), "bravo")).containsExactly(CHARLIE);
        assertThat(names(rt, new Where.IgnoreCase(new Where.Gte(n)), "bravo")).containsExactly(BRAVO, CHARLIE);
        assertThat(names(rt, new Where.IgnoreCase(new Where.Between(n)), "b", "c")).containsExactly(BRAVO);
        assertThat(names(rt, new Where.IgnoreCase(new Where.In(n, 2)), "ALPHA", "charlie"))
                .as(name).containsExactly(ALPHA, CHARLIE);
        assertThat(names(rt, new Where.IgnoreCase(new Where.Not(new Where.Eq(n))), "ALPHA"))
                .containsExactly(BRAVO, CHARLIE);
        Where unsupported = new Where.IgnoreCase(new Where.IsNull(n));
        assertThatThrownBy(() -> names(rt, unsupported)).isInstanceOf(IllegalArgumentException.class);
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("dialects")
    void rendersScalarFunctionComparisons(String name, Dialect dialect, String url) throws SQLException {
        RepositoryRuntime rt = runtime(dialect, url);
        Attribute<?, ?> n = _Author.name;

        assertThat(names(rt, new Where.Func("LENGTH", new Where.NotEq(n)), 5)).containsExactly(CHARLIE);
        assertThat(names(rt, new Where.Func("LENGTH", new Where.Lt(n)), 6)).containsExactly(ALPHA, BRAVO);
        assertThat(names(rt, new Where.Func("LENGTH", new Where.Lte(n)), 5)).containsExactly(ALPHA, BRAVO);
        assertThat(names(rt, new Where.Func("LENGTH", new Where.Gt(n)), 5)).containsExactly(CHARLIE);
        assertThat(names(rt, new Where.Func("LENGTH", new Where.Gte(n)), 7)).containsExactly(CHARLIE);
        assertThat(names(rt, new Where.Func("UPPER", new Where.IsNotNull(n)))).hasSize(3);
        assertThat(names(rt, new Where.Func("UPPER", new Where.Not(new Where.Eq(n))), "BRAVO"))
                .as(name).containsExactly(ALPHA, CHARLIE);
        assertThat(names(rt, Where.ALWAYS_TRUE)).hasSize(3);
        Where unsupported = new Where.Func("UPPER", new Where.And(List.of(new Where.Eq(n), new Where.Eq(n))));
        assertThatThrownBy(() -> names(rt, unsupported)).isInstanceOf(IllegalArgumentException.class);
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("dialects")
    void joinsAlongARelationPath(String name, Dialect dialect, String url) throws SQLException {
        RepositoryRuntime rt = runtime(dialect, url);
        Attribute<?, ?> authorName = PathResolver.resolve(_Book.$MODEL, "author.name");

        List<Book> books = rt.queryList(_Book.$MODEL, new Where.Eq(authorName),
                new OrderBy(List.of(OrderBy.Order.desc(authorName))), BRAVO);
        assertThat(books).extracting(Book::getTitle).as(name).containsExactly("Second");
        assertThat(rt.countWhere(_Book.$MODEL, new Where.Like(authorName), "%a%")).isEqualTo(2);
        assertThat(rt.queryList(_Book.$MODEL, new Where.IsNotNull(_Book.publishedOn), OrderBy.NONE))
                .extracting(Book::getPublishedOn).containsExactly(LocalDate.of(2020, 1, 1));
        Where joined = new Where.Eq(authorName);
        assertThatThrownBy(() -> rt.deleteWhere(_Book.$MODEL, joined, ALPHA))
                .isInstanceOf(IllegalStateException.class);
    }
}
