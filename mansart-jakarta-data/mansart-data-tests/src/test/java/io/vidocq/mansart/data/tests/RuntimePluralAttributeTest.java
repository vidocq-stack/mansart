package io.vidocq.mansart.data.tests;

import io.vidocq.mansart.data.core.MansartData;
import io.vidocq.mansart.data.core.RuntimeEntityModelBuilder;
import io.vidocq.mansart.data.dialect.Attribute;
import jakarta.data.repository.BasicRepository;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.Statement;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * The run-time path builds the same model as the processor: a plural attribute is not a column, so a repository
 * reads and writes an entity that has one against a table without it (MANSART-049, Noether BUG-20261111-06).
 */
class RuntimePluralAttributeTest {

    /** Not annotated {@code @Repository}: only the runtime engine implements it. */
    public interface Shelves extends BasicRepository<PluralShelf, Long> {
    }

    @Test
    void theRuntimeModelLeavesPluralAttributesOut() {
        assertThat(RuntimeEntityModelBuilder.build(PluralShelf.class).attributes())
                .extracting(Attribute::name).containsExactly("id", "name");
    }

    @Test
    void aRepositorySavesAndFindsAnEntityThatHasACollection() throws Exception {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:mansart-runtime-plural;DB_CLOSE_DELAY=-1");
        ds.setUser("sa");
        try (Connection c = ds.getConnection(); Statement s = c.createStatement()) {
            s.execute("DROP TABLE IF EXISTS \"plural_shelf\"");
            s.execute("CREATE TABLE \"plural_shelf\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + " \"name\" VARCHAR(200))");
        }
        Shelves shelves = MansartData.builder().dataSource(ds).build().runtimeRepository(Shelves.class);
        PluralShelf shelf = new PluralShelf();
        shelf.name = "fiction";
        shelf.tags.add("novel");

        Long id = shelves.save(shelf).id;

        PluralShelf found = shelves.findById(id).orElseThrow();
        assertThat(found.name).isEqualTo("fiction");
        assertThat(found.tags).isEmpty();
    }
}
