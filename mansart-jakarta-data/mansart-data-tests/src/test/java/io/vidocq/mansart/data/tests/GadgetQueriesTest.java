/**
 * Runs every query shape of {@link GadgetRepository} through both implementations of the repository: the class
 * the annotation processor generated ({@link MansartData#repository}) and the runtime proxy
 * ({@link MansartData#runtimeRepository}). Both must give the results Jakarta Data 1.0 specifies.
 */
class GadgetQueriesTest {

    private static final String ANVIL = "Anvil";
    private static final String BOLT = "Bolt";
    private static final String COMPASS = "Compass";
    private static final String DRONE = "Drone";
    private static final String EASEL = "Easel";
    private static final String TOOLS = "tools";
    private static final String TOYS = "toys";
    private static final String NAME = "name";
    private static final String FAN = "Fan";
    private static final String ZED = "Zed";

    /** One database, with a repository factory for each implementation. */
    private record Stack(DataSource dataSource, MansartData generated, MansartData runtime) {

        static Stack of(String url, Dialect dialect) {
            JdbcDataSource ds = new JdbcDataSource();
            ds.setURL(url);
            ds.setUser("sa");
            MansartData.Builder generated = MansartData.builder().dataSource(ds);
            MansartData.Builder runtime = MansartData.builder().dataSource(ds);
            if (dialect != null) {
                generated.dialect(dialect);
                runtime.dialect(dialect);
            }
            return new Stack(ds, generated.build(), runtime.build());
        }
    }

    private static Stack h2;
    /** The PostgreSQL dialect on H2 in its PostgreSQL compatibility mode: the SQL it renders, run by a database. */
    private static Stack postgresql;

    @BeforeAll
    static void initStacks() {
        h2 = Stack.of("jdbc:h2:mem:mansart-gadgets;DB_CLOSE_DELAY=-1", null);
        postgresql = Stack.of("jdbc:h2:mem:mansart-gadgets-pg;MODE=PostgreSQL;DB_CLOSE_DELAY=-1",
                new PostgresqlDialect());
    }

    static Stream<Named<GadgetRepository>> repositories() {
        return Stream.of(
                Named.of("annotation processor", h2.generated().repository(GadgetRepository.class)),
                Named.of("runtime proxy", h2.runtime().runtimeRepository(GadgetRepository.class)),
                Named.of("annotation processor, PostgreSQL dialect",
                        postgresql.generated().repository(GadgetRepository.class)),
                Named.of("runtime proxy, PostgreSQL dialect",
                        postgresql.runtime().runtimeRepository(GadgetRepository.class)));
    }

    @BeforeEach
    void resetData() throws Exception {
        for (Stack stack : List.of(h2, postgresql)) {
            try (Connection c = stack.dataSource().getConnection(); Statement s = c.createStatement()) {
                s.execute("DROP TABLE IF EXISTS \"gadgets\"");
                s.execute("CREATE TABLE \"gadgets\" ("
                        + "\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                        + "\"name\" VARCHAR(100) NOT NULL, \"category\" VARCHAR(100), \"price\" DOUBLE PRECISION, "
                        + "\"stock\" INT, \"active\" BOOLEAN, \"released_on\" DATE)");
            }
            stack.generated().repository(GadgetRepository.class).addAll(List.of(
                    new Gadget(ANVIL, TOOLS, 30.0, 5, true, LocalDate.of(2024, 1, 10)),
                    new Gadget(BOLT, TOOLS, 0.5, 500, true, LocalDate.of(2023, 5, 1)),
                    new Gadget(COMPASS, null, 12.0, 0, false, null),
                    new Gadget(DRONE, TOYS, 250.0, 3, true, LocalDate.of(2025, 2, 2)),
                    new Gadget(EASEL, null, 45.0, 12, false, LocalDate.of(2022, 9, 9))));
        }
    }

    private static List<String> names(Iterable<Gadget> gadgets) {
        return StreamSupport.stream(gadgets.spliterator(), false).map(Gadget::getName).toList();
    }

    private static List<String> names(Stream<Gadget> gadgets) {
        return gadgets.map(Gadget::getName).toList();
    }

    /* ---- derived queries ---- */

    @ParameterizedTest
    @MethodSource("repositories")
    void derivedComparators(GadgetRepository repo) {
        assertThat(names(repo.findByPriceBetween(10, 50))).containsExactlyInAnyOrder(ANVIL, COMPASS, EASEL);
        assertThat(names(repo.findByCategoryIsNull())).containsExactlyInAnyOrder(COMPASS, EASEL);
        assertThat(names(repo.findByCategoryIsNotNull())).containsExactlyInAnyOrder(ANVIL, BOLT, DRONE);
        assertThat(names(repo.findByActiveTrue())).containsExactlyInAnyOrder(ANVIL, BOLT, DRONE);
        assertThat(names(repo.findByActiveFalse())).containsExactlyInAnyOrder(COMPASS, EASEL);
        assertThat(names(repo.findByStockLessThan(5))).containsExactlyInAnyOrder(COMPASS, DRONE);
        assertThat(names(repo.findByStockLessThanEqual(5))).containsExactlyInAnyOrder(ANVIL, COMPASS, DRONE);
        assertThat(names(repo.findByStockGreaterThan(12))).containsExactly(BOLT);
        assertThat(names(repo.findByStockGreaterThanEqual(12))).containsExactlyInAnyOrder(BOLT, EASEL);
        assertThat(names(repo.findByStockLessThanOrStockGreaterThan(3, 100))).containsExactlyInAnyOrder(COMPASS, BOLT);
    }

    @ParameterizedTest
    @MethodSource("repositories")
    void derivedTextMatches(GadgetRepository repo) {
        assertThat(names(repo.findByNameContains("o"))).containsExactlyInAnyOrder(BOLT, COMPASS, DRONE);
        assertThat(names(repo.findByNameStartsWith("D"))).containsExactly(DRONE);
        assertThat(names(repo.findByNameEndsWith("l"))).containsExactlyInAnyOrder(ANVIL, EASEL);
        assertThat(names(repo.findByNameIgnoreCase("bOLT"))).containsExactly(BOLT);
        assertThat(names(repo.findByNameNot(BOLT))).containsExactlyInAnyOrder(ANVIL, COMPASS, DRONE, EASEL);
        assertThat(repo.existsByNameIgnoreCase("easel")).isTrue();
        assertThat(repo.existsByNameIgnoreCase("zebra")).isFalse();
    }

    @ParameterizedTest
    @MethodSource("repositories")
    void derivedInWithCollections(GadgetRepository repo) {
        assertThat(names(repo.findByNameIn(List.of(ANVIL, DRONE, "Nope")))).containsExactlyInAnyOrder(ANVIL, DRONE);
        assertThat(repo.findByNameIn(List.of())).isEmpty();
        assertThat(names(repo.findByCategoryIn(Set.of(TOYS)))).containsExactly(DRONE);
        assertThat(repo.findByCategoryIn(Set.of())).isEmpty();
        assertThat(repo.findOneByNameIn(Set.of(EASEL))).get().extracting(Gadget::getName).isEqualTo(EASEL);
        assertThat(repo.findOneByNameIn(Set.of())).isEmpty();
        assertThat(repo.countByNameIn(List.of(ANVIL, BOLT))).isEqualTo(2);
        assertThat(repo.countByNameIn(List.of())).isZero();
        assertThat(repo.existsByNameIn(List.of(BOLT))).isTrue();
        assertThat(repo.existsByNameIn(List.of(ZED))).isFalse();
        assertThat(repo.existsByNameIn(List.of())).isFalse();
        assertThat(repo.deleteByNameIn(List.of())).isZero();
        assertThat(repo.deleteByNameIn(List.of(ANVIL))).isEqualTo(1);
        assertThat(names(repo.findAll())).containsExactlyInAnyOrder(BOLT, COMPASS, DRONE, EASEL);
    }

    @ParameterizedTest
    @MethodSource("repositories")
    void derivedCountsAndDeletes(GadgetRepository repo) {
        assertThat(repo.countByActiveTrue()).isEqualTo(3);
        assertThat(repo.deleteByCategoryIsNull()).isEqualTo(2);
        repo.removeByName(BOLT);
        assertThat(names(repo.findAll())).containsExactlyInAnyOrder(ANVIL, DRONE);
    }

    @ParameterizedTest
    @MethodSource("repositories")
    void derivedReturnShapes(GadgetRepository repo) {
        assertThat(repo.findByName(DRONE).getStock()).isEqualTo(3);
        assertThat(names(repo.findByCategory(TOOLS))).containsExactlyInAnyOrder(ANVIL, BOLT);
        assertThat(names(repo.findByActive(false))).containsExactlyInAnyOrder(COMPASS, EASEL);
        assertThat(names(repo.findByStock(0))).containsExactly(COMPASS);
        assertThat(repo.findFirstByOrderByPriceDesc()).get().extracting(Gadget::getName).isEqualTo(DRONE);
        assertThat(names(repo.findFirst2ByActiveTrueOrderByPriceAsc())).containsExactly(BOLT, ANVIL);
    }

    @ParameterizedTest
    @MethodSource("repositories")
    void derivedPages(GadgetRepository repo) {
        Page<Gadget> first = repo.findByActiveOrderByNameAsc(true, PageRequest.ofSize(2));
        assertThat(names(first.content())).containsExactly(ANVIL, BOLT);
        assertThat(first.totalElements()).isEqualTo(3);
        assertThat(names(repo.findByActiveOrderByNameAsc(true, first.nextPageRequest()).content()))
                .containsExactly(DRONE);

        CursoredPage<Gadget> start = repo.findByStockGreaterThanOrderByStockAsc(0, PageRequest.ofSize(2));
        assertThat(names(start.content())).containsExactly(DRONE, ANVIL);
        CursoredPage<Gadget> next = repo.findByStockGreaterThanOrderByStockAsc(0, start.nextPageRequest());
        assertThat(names(next.content())).containsExactly(EASEL, BOLT);
    }

    /* ---- @Query ---- */

    @ParameterizedTest
    @MethodSource("repositories")
    void queryPredicates(GadgetRepository repo) {
        assertThat(names(repo.pricedBetween(10, 50))).containsExactly(EASEL, ANVIL, COMPASS);
        assertThat(names(repo.uncategorised())).containsExactly(COMPASS, EASEL);
        assertThat(names(repo.categorisedAndNot(false))).containsExactly(ANVIL, BOLT, DRONE);
        assertThat(names(repo.stockOutside(3, 100))).containsExactly(COMPASS, BOLT);
        assertThat(names(repo.stockWindow(0, 12, ANVIL, DRONE))).containsExactly(EASEL);
        assertThat(names(repo.namedEither(BOLT, EASEL))).containsExactly(BOLT, EASEL);
        assertThat(names(repo.namedAnyOf(List.of(DRONE, ANVIL)))).containsExactly(ANVIL, DRONE);
        assertThat(repo.namedAnyOf(List.of())).isEmpty();
    }

    @ParameterizedTest
    @MethodSource("repositories")
    void queryScalarFunctions(GadgetRepository repo) {
        assertThat(repo.byUpperName("DRONE")).get().extracting(Gadget::getName).isEqualTo(DRONE);
        assertThat(names(repo.byLowerNameLike("%a%"))).containsExactly(ANVIL, COMPASS, EASEL);
        assertThat(names(repo.byNameLength(4, 5))).containsExactly(ANVIL, BOLT, DRONE, EASEL);
        assertThat(names(repo.byUpperCategoryNull())).containsExactly(COMPASS, EASEL);
        assertThat(names(repo.byUpperNameEither("BOLT", "ANVIL"))).containsExactly(ANVIL, BOLT);
        assertThat(names(repo.byLowerNameAnyOf(List.of("easel", "compass")))).containsExactly(COMPASS, EASEL);
        assertThat(names(repo.busyOrCheap(100, TOYS, 300.0))).containsExactly(BOLT, DRONE);
    }

    @ParameterizedTest
    @MethodSource("repositories")
    void queryMixingACollectionInWithFunctionsAndRanges(GadgetRepository repo) {
        assertThat(names(repo.namedAmongInWindows(List.of(ANVIL, BOLT, DRONE, EASEL), "BOLT", 1, 10, 4, 5,
                List.of(TOOLS, TOYS)))).containsExactly(ANVIL, DRONE);
    }

    @ParameterizedTest
    @MethodSource("repositories")
    void queryReturnShapes(GadgetRepository repo) {
        assertThat(repo.exactlyNamed(ANVIL).getPrice()).isEqualTo(30.0);
        assertThat(repo.countByFlag(true)).isEqualTo(3);
        assertThat(repo.nameTaken(BOLT)).isTrue();
        assertThat(repo.nameTaken(ZED)).isFalse();
        assertThat(repo.countActive(false)).isEqualTo(2);

        Page<Gadget> page = repo.activePage(true, PageRequest.ofSize(2));
        assertThat(names(page.content())).containsExactly(ANVIL, BOLT);
        assertThat(page.totalElements()).isEqualTo(3);
        CursoredPage<Gadget> cursor = repo.activeCursor(true, PageRequest.ofSize(2));
        assertThat(names(cursor.content())).containsExactly(ANVIL, BOLT);
        assertThat(names(repo.activeCursor(true, cursor.nextPageRequest()).content())).containsExactly(DRONE);
    }

    @ParameterizedTest
    @MethodSource("repositories")
    void queryProjectionsAndAggregates(GadgetRepository repo) {
        assertThat(repo.activeNames(false)).containsExactly(COMPASS, EASEL);
        assertThat(repo.namesInStockAbove(4)).containsExactly(ANVIL, BOLT, EASEL);
        assertThat(repo.categoryOf(DRONE)).contains(TOYS);
        assertThat(repo.categoryOf(ZED)).isEmpty();
        assertThat(repo.stockOf(BOLT)).isEqualTo(500);
        assertThat(repo.priceOf(DRONE)).isEqualTo(250.0);
        assertThat(repo.nameAndStock(true)).containsExactly(
                new Object[]{ANVIL, 5}, new Object[]{BOLT, 500}, new Object[]{DRONE, 3});
        assertThat(repo.totalStock(true)).isEqualTo(508);
        assertThat(repo.averagePrice(false)).isEqualTo(28.5);
        assertThat(repo.highestPrice(TOOLS)).isEqualTo(30.0);
        assertThat(repo.highestPrice("none")).isNull();
        assertThat(repo.firstName(true)).isEqualTo(ANVIL);
    }

    @ParameterizedTest
    @MethodSource("repositories")
    void queryUpdatesAndDeletes(GadgetRepository repo) {
        assertThat(repo.restock(7, COMPASS)).isEqualTo(1);
        assertThat(repo.stockOf(COMPASS)).isEqualTo(7);
        repo.activateCategory(false, TOOLS);
        assertThat(repo.countByActiveTrue()).isEqualTo(1);
        assertThat(repo.addStock(10, DRONE)).isEqualTo(1);
        assertThat(repo.stockOf(DRONE)).isEqualTo(13);
        repo.scalePrices(2.0, TOYS);
        assertThat(repo.priceOf(DRONE)).isEqualTo(500.0);
        assertThat(repo.deleteWithStock(12)).isEqualTo(1);
        repo.deleteCategory(TOOLS);
        assertThat(names(repo.findAll())).containsExactlyInAnyOrder(COMPASS, DRONE);
    }

    /* ---- @Find ---- */

    @ParameterizedTest
    @MethodSource("repositories")
    void findWithByAndOrderBy(GadgetRepository repo) {
        assertThat(names(repo.inCategory(TOOLS))).containsExactly(BOLT, ANVIL);
        assertThat(names(repo.allByActivityThenPrice())).containsExactly(EASEL, COMPASS, DRONE, ANVIL, BOLT);
        assertThat(repo.named(EASEL)).get().extracting(Gadget::getStock).isEqualTo(12);
        assertThat(repo.named(ZED)).isEmpty();
    }

    /* ---- lifecycle and built-in methods ---- */

    @ParameterizedTest
    @MethodSource("repositories")
    void lifecycleAnnotations(GadgetRepository repo) {
        Gadget fan = repo.add(new Gadget(FAN, TOYS, 20.0, 4, true, null));
        assertThat(fan.getId()).isNotNull();
        assertThat(repo.addAll(List.of(new Gadget("Gong", TOYS, 9.0, 1, true, null))))
                .singleElement().extracting(Gadget::getId).isNotNull();

        fan.setPrice(25.0);
        assertThat(repo.change(fan).getPrice()).isEqualTo(25.0);
        assertThat(repo.priceOf(FAN)).isEqualTo(25.0);

        repo.drop(fan);
        assertThat(repo.findById(fan.getId())).isEmpty();
        Gadget ghost = new Gadget("Ghost", null, 1.0, 1, false, null);
        ghost.setId(-5L);
        assertThatThrownBy(() -> repo.change(ghost)).isInstanceOf(OptimisticLockingFailureException.class);
    }

    /**
     * {@code @Save} of an entity that has an id upserts: the PostgreSQL dialect's {@code INSERT … ON CONFLICT DO
     * UPDATE} is beyond H2's PostgreSQL mode, so this one runs on the H2 dialect only.
     */
    @ParameterizedTest
    @MethodSource("h2Repositories")
    void saveUpsertsAnExistingEntity(GadgetRepository repo) {
        Gadget fan = repo.add(new Gadget(FAN, TOYS, 20.0, 4, true, null));
        fan.setStock(40);

        assertThat(repo.store(fan).getId()).isEqualTo(fan.getId());
        assertThat(repo.stockOf(FAN)).isEqualTo(40);
    }

    static Stream<Named<GadgetRepository>> h2Repositories() {
        return repositories().limit(2);
    }

    @ParameterizedTest
    @MethodSource("repositories")
    void builtInMethods(GadgetRepository repo) {
        Page<Gadget> page = repo.findAll(PageRequest.ofSize(3), Order.by(Sort.desc(NAME)));
        assertThat(names(page.content())).containsExactly(EASEL, DRONE, COMPASS);
        assertThat(page.totalElements()).isEqualTo(5);

        List<Gadget> saved = repo.saveAll(List.of(new Gadget("Gear", TOOLS, 2.0, 9, true, null),
                new Gadget("Hook", TOOLS, 1.0, 8, true, null)));
        assertThat(saved).allSatisfy(g -> assertThat(g.getId()).isNotNull());
        repo.deleteAll(saved);
        assertThat(repo.findByCategory(TOOLS)).hasSize(2);
        repo.deleteById(repo.findByName(BOLT).getId());
        assertThat(names(repo.findByCategory(TOOLS))).containsExactly(ANVIL);
    }
}
