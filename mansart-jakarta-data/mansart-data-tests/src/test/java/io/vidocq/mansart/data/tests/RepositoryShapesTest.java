package io.vidocq.mansart.data.tests;

import io.vidocq.mansart.data.core.MansartData;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;

import javax.sql.DataSource;
import java.lang.reflect.Proxy;
import java.sql.Connection;
import java.sql.Statement;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Repository shapes the generated implementation and the runtime one must serve alike (Jakarta Data 1.0 §4): a
 * repository that parameterizes a generic repository contract, and one that implements an inherited method with a
 * default body. The runtime one is a generated class, not a {@link Proxy}.
 */
class RepositoryShapesTest {

    private static DataSource dataSource;
    private static MansartData mansartData;

    @BeforeAll
    static void initStack() {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:mansart-shapes;DB_CLOSE_DELAY=-1");
        ds.setUser("sa");
        dataSource = ds;
        mansartData = MansartData.builder().dataSource(ds).build();
    }

    @BeforeEach
    void resetSchema() throws Exception {
        try (Connection c = dataSource.getConnection(); Statement s = c.createStatement()) {
            s.execute("DROP TABLE IF EXISTS \"articles\"");
            s.execute("CREATE TABLE \"articles\" ("
                    + "  \"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + "  \"title\" VARCHAR(300) NOT NULL,"
                    + "  \"version\" INTEGER NOT NULL DEFAULT 0"
                    + ")");
        }
    }

    private static <R> R repository(Class<R> type, boolean runtime) {
        R repository = runtime ? mansartData.runtimeRepository(type) : mansartData.repository(type);
        assertThat(Proxy.isProxyClass(repository.getClass())).as("a generated class, not a dynamic proxy").isFalse();
        return repository;
    }

    @ParameterizedTest(name = "runtime={0}")
    @ValueSource(booleans = {false, true})
    void aRepositoryOfAGenericContractKnowsItsEntity(boolean runtime) {
        GenericArticleRepository repo = repository(GenericArticleRepository.class, runtime);
        Article article = new Article();
        article.setTitle("Generic");
        article.setVersion(0);

        Article saved = repo.insert(article);

        assertThat(repo.findById(saved.getId())).map(Article::getTitle).contains("Generic");
    }

    @ParameterizedTest(name = "runtime={0}")
    @ValueSource(booleans = {false, true})
    void aDefaultBodyImplementsTheInheritedMethod(boolean runtime) {
        DefaultedArticleRepository repo = repository(DefaultedArticleRepository.class, runtime);

        assertThat(repo.featured()).isEmpty();
    }
}
