package io.vidocq.mansart.data.tests;

import io.vidocq.mansart.data.core.MansartData;
import jakarta.data.exceptions.EmptyResultException;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Named;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.MethodSource;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.Statement;
import java.util.stream.Stream;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * MANSART-013: the {@code First} keyword of a derived query keeps the first result(s) in the {@code OrderBy} order,
 * through the annotation-processor implementation as through the runtime proxy.
 */
class DerivedFirstTest {

    private static DataSource dataSource;
    private static MansartData generatedData;
    private static MansartData runtimeData;

    @BeforeAll
    static void initStack() {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:mansart-first;DB_CLOSE_DELAY=-1");
        ds.setUser("sa");
        dataSource = ds;
        generatedData = MansartData.builder().dataSource(ds).build();
        runtimeData = MansartData.builder().dataSource(ds).build();
    }

    static Stream<Named<AuthorRepository>> repositories() {
        return Stream.of(
                Named.of("annotation processor", generatedData.repository(AuthorRepository.class)),
                Named.of("runtime proxy", runtimeData.runtimeRepository(AuthorRepository.class)));
    }

    @BeforeEach
    void resetSchema() throws Exception {
        try (Connection c = dataSource.getConnection(); Statement s = c.createStatement()) {
            s.execute("DROP TABLE IF EXISTS \"authors\"");
            s.execute("CREATE TABLE \"authors\" ("
                    + "  \"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + "  \"name\" VARCHAR(200) NOT NULL"
                    + ")");
        }
        AuthorRepository repo = generatedData.repository(AuthorRepository.class);
        for (String name : new String[]{"Bravo", "Alpha", "Charlie", "Alfred"}) {
            Author a = new Author();
            a.setName(name);
            repo.save(a);
        }
    }

    @ParameterizedTest
    @MethodSource("repositories")
    void findFirstKeepsTheFirstOfSeveralMatches(AuthorRepository repo) {
        assertThat(repo.findFirstByOrderByNameDesc()).get().extracting(Author::getName).isEqualTo("Charlie");
        assertThat(repo.findFirstByNameStartsWithOrderByNameAsc("Al").getName()).isEqualTo("Alfred");
    }

    @ParameterizedTest
    @MethodSource("repositories")
    void findFirstNKeepsAtMostNResults(AuthorRepository repo) {
        assertThat(repo.findFirst2ByNameNotOrderByNameAsc("Alfred")).extracting(Author::getName)
                .containsExactly("Alpha", "Bravo");
    }

    /** MANSART-019: a single-entity {@code findFirst} without a match throws, it does not return {@code null}. */
    @ParameterizedTest
    @MethodSource("repositories")
    void findFirstWithoutAMatchThrowsEmptyResultException(AuthorRepository repo) {
        assertThat(repo.findFirstByOrderByNameDesc()).isPresent();
        assertThatThrownBy(() -> repo.findFirstByNameStartsWithOrderByNameAsc("Zz"))
                .isInstanceOf(EmptyResultException.class);
    }
}
