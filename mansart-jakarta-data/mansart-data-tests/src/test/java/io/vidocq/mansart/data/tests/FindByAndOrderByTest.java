package io.vidocq.mansart.data.tests;

import io.vidocq.mansart.data.core.MansartData;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Named;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.MethodSource;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.Statement;
import java.util.stream.Stream;

import static org.assertj.core.api.Assertions.assertThat;

/** MANSART-018: {@code @Find} honours {@code @By} and {@code @OrderBy}, through both implementations. */
class FindByAndOrderByTest {

    private static DataSource dataSource;
    private static MansartData generatedData;
    private static MansartData runtimeData;

    @BeforeAll
    static void initStack() {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:mansart-find-by;DB_CLOSE_DELAY=-1");
        ds.setUser("sa");
        dataSource = ds;
        generatedData = MansartData.builder().dataSource(ds).build();
        runtimeData = MansartData.builder().dataSource(ds).build();
    }

    static Stream<Named<LabSeatRepository>> repositories() {
        return Stream.of(
                Named.of("annotation processor", generatedData.repository(LabSeatRepository.class)),
                Named.of("runtime proxy", runtimeData.runtimeRepository(LabSeatRepository.class)));
    }

    @BeforeEach
    void resetSchema() throws Exception {
        try (Connection c = dataSource.getConnection(); Statement s = c.createStatement()) {
            s.execute("DROP TABLE IF EXISTS \"lab_seats\"");
            s.execute("CREATE TABLE \"lab_seats\" ("
                    + "  \"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + "  \"room_id\" VARCHAR(36) NOT NULL,"
                    + "  \"seat_row\" INTEGER NOT NULL,"
                    + "  \"seat_block_index\" INTEGER NOT NULL,"
                    + "  \"released\" BOOLEAN NOT NULL"
                    + ")");
        }
        LabSeatRepository repo = generatedData.repository(LabSeatRepository.class);
        int[][] rowAndBlock = {{1, 7}, {3, 7}, {2, 8}, {2, 7}};
        for (int[] seat : rowAndBlock) {
            LabSeat s = new LabSeat();
            s.setRoomId("room");
            s.setSeatRow(seat[0]);
            s.setSeatBlockIndex(seat[1]);
            repo.save(s);
        }
    }

    @ParameterizedTest
    @MethodSource("repositories")
    void bindsByAndOrdersByOrderBy(LabSeatRepository repo) {
        assertThat(repo.inBlock(7)).extracting(LabSeat::getSeatRow).containsExactly(3, 2, 1);
        assertThat(repo.inBlock(8)).extracting(LabSeat::getSeatRow).containsExactly(2);
    }

    @ParameterizedTest
    @MethodSource("repositories")
    void bindsTheIdThroughById(LabSeatRepository repo) {
        LabSeat third = repo.inBlock(8).get(0);

        assertThat(repo.seat(third.getId())).get().extracting(LabSeat::getSeatBlockIndex).isEqualTo(8);
        assertThat(repo.seat(-1L)).isEmpty();
    }
}
