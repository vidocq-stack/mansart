package io.vidocq.mansart.data.tests;

import io.vidocq.mansart.data.core.MansartData;
import jakarta.data.exceptions.EmptyResultException;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Named;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.MethodSource;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.Statement;
import java.util.stream.Stream;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * MANSART-014: a repository method returning a single entity or value throws Jakarta Data's
 * {@link EmptyResultException} when nothing matches, through both implementations.
 */
class EmptySingleResultTest {

    private static DataSource dataSource;
    private static MansartData generatedData;
    private static MansartData runtimeData;

    @BeforeAll
    static void initStack() {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:mansart-empty-single;DB_CLOSE_DELAY=-1");
        ds.setUser("sa");
        dataSource = ds;
        generatedData = MansartData.builder().dataSource(ds).build();
        runtimeData = MansartData.builder().dataSource(ds).build();
    }

    static Stream<Named<AuthorRepository>> repositories() {
        return Stream.of(
                Named.of("annotation processor", generatedData.repository(AuthorRepository.class)),
                Named.of("runtime proxy", runtimeData.runtimeRepository(AuthorRepository.class)));
    }

    @BeforeEach
    void resetSchema() throws Exception {
        try (Connection c = dataSource.getConnection(); Statement s = c.createStatement()) {
            s.execute("DROP TABLE IF EXISTS \"authors\"");
            s.execute("CREATE TABLE \"authors\" ("
                    + "  \"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + "  \"name\" VARCHAR(200) NOT NULL"
                    + ")");
        }
        Author a = new Author();
        a.setName("Solo");
        generatedData.repository(AuthorRepository.class).save(a);
    }

    @ParameterizedTest
    @MethodSource("repositories")
    void singleResultsAreReturned(AuthorRepository repo) {
        Author solo = repo.jdqlOneNamed("Solo");

        assertThat(repo.findByIdGreaterThan(solo.getId() - 1)).extracting(Author::getName).isEqualTo("Solo");
        assertThat(repo.jdqlNameOfId(solo.getId())).isEqualTo("Solo");
    }

    @ParameterizedTest
    @MethodSource("repositories")
    void missingSingleResultsThrowEmptyResultException(AuthorRepository repo) {
        assertThatThrownBy(() -> repo.findByIdGreaterThan(1_000_000L)).isInstanceOf(EmptyResultException.class);
        assertThatThrownBy(() -> repo.jdqlOneNamed("nobody")).isInstanceOf(EmptyResultException.class);
        assertThatThrownBy(() -> repo.jdqlNameOfId(-1L)).isInstanceOf(EmptyResultException.class);
    }
}
