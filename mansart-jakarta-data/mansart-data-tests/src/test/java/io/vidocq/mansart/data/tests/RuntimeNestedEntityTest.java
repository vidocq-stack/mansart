package io.vidocq.mansart.data.tests;

import io.vidocq.mansart.data.core.MansartData;
import jakarta.data.repository.BasicRepository;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.Statement;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * A static nested entity is compiled with its metamodel and served like a top-level one (MANSART-050): this test
 * class compiles, where the processor used to write {@code _Crate} into a package named after the outer class.
 * Other tests of this package have a nested {@code Crate} of their own: none of them gets this one's metamodel.
 */
class RuntimeNestedEntityTest {

    @Entity
    @Table(name = "nested_crate")
    public static class Crate {
        @Id @GeneratedValue public Long id;
        public String label;
    }

    /** Not annotated {@code @Repository}: only the runtime engine implements it. */
    public interface Crates extends BasicRepository<Crate, Long> {
    }

    @Test
    void theMetamodelOfANestedEntityIsInItsPackage() throws Exception {
        Class<?> metamodel = Class.forName("io.vidocq.mansart.data.tests._RuntimeNestedEntityTest_Crate");

        assertThat(metamodel.getPackageName()).isEqualTo(Crate.class.getPackageName());
    }

    @Test
    void aRepositorySavesAndFindsANestedEntity() throws Exception {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:mansart-runtime-nested;DB_CLOSE_DELAY=-1");
        ds.setUser("sa");
        try (Connection c = ds.getConnection(); Statement s = c.createStatement()) {
            s.execute("DROP TABLE IF EXISTS \"nested_crate\"");
            s.execute("CREATE TABLE \"nested_crate\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + " \"label\" VARCHAR(200))");
        }
        Crates crates = MansartData.builder().dataSource(ds).build().runtimeRepository(Crates.class);
        Crate crate = new Crate();
        crate.label = "books";

        Long id = crates.save(crate).id;

        assertThat(crates.findById(id).orElseThrow().label).isEqualTo("books");
    }
}
