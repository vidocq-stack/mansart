package io.vidocq.mansart.data.tests;

import io.vidocq.vauban.core.container.VaubanContainer;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.Statement;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * A library ships the implementation another Jakarta Data provider generated for its repository ({@code ShelfNotes_},
 * Hibernate Processor's convention) and Mansart implements the same repository (mansart#40): the foreign class is
 * vetoed, so the repository is Mansart's alone — not ambiguous, and not a bean that needs the other provider.
 */
class ForeignImplementationTest {

    private static VaubanContainer container;

    @BeforeAll
    static void boot() throws Exception {
        try (Connection c = BridgeDataSources.h2(BridgeDataSources.DEFAULT_URL).getConnection();
             Statement s = c.createStatement()) {
            s.execute("CREATE TABLE IF NOT EXISTS \"shelf_notes\" ("
                    + "  \"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + "  \"text\" VARCHAR(200))");
        }
        container = VaubanContainer.builder()
                .addBeanClass(io.vidocq.mansart.data.cdi.MansartDataExtension.class)
                .addBeanClass(io.vidocq.mansart.data.cdi.MansartRuntimeProducer.class)
                .addBeanClass(BridgeDataSources.class)
                .addBeanClass(ShelfNote.class)
                .addBeanClass(ShelfNotes.class)
                .addBeanClass(ShelfNotesImpl.class)
                .addBeanClass(ShelfNotes_.class)
                .build();
    }

    @AfterAll
    static void shutdown() {
        if (container != null) container.close();
    }

    @Test
    void theRepositoryIsMansartsAndWorks() {
        ShelfNotes notes = container.select(ShelfNotes.class);
        ShelfNote note = new ShelfNote();
        note.setText("foreign-impl");
        notes.save(note);

        assertThat(notes).isNotInstanceOf(ShelfNotes_.class);
        assertThat(notes.countByText("foreign-impl")).isEqualTo(1L);
    }
}
