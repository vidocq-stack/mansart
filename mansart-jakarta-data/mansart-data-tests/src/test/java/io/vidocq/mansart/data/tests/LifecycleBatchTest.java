package io.vidocq.mansart.data.tests;

import io.vidocq.mansart.data.core.MansartData;
import jakarta.data.exceptions.OptimisticLockingFailureException;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Named;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.MethodSource;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.Statement;
import java.util.List;
import java.util.stream.Stream;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/** MANSART-016: lifecycle methods taking a list or an array of entities, through both implementations. */
class LifecycleBatchTest {

    private static DataSource dataSource;
    private static MansartData generatedData;
    private static MansartData runtimeData;

    @BeforeAll
    static void initStack() {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:mansart-lifecycle-batch;DB_CLOSE_DELAY=-1");
        ds.setUser("sa");
        dataSource = ds;
        generatedData = MansartData.builder().dataSource(ds).build();
        runtimeData = MansartData.builder().dataSource(ds).build();
    }

    static Stream<Named<ArticleBatchRepository>> repositories() {
        return Stream.of(
                Named.of("annotation processor", generatedData.repository(ArticleBatchRepository.class)),
                Named.of("runtime proxy", runtimeData.runtimeRepository(ArticleBatchRepository.class)));
    }

    @BeforeEach
    void resetSchema() throws Exception {
        try (Connection c = dataSource.getConnection(); Statement s = c.createStatement()) {
            s.execute("DROP TABLE IF EXISTS \"articles\"");
            s.execute("CREATE TABLE \"articles\" ("
                    + "  \"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + "  \"title\" VARCHAR(300) NOT NULL,"
                    + "  \"version\" INTEGER NOT NULL DEFAULT 0"
                    + ")");
        }
    }

    private static Article article(String title) {
        Article a = new Article();
        a.setTitle(title);
        a.setVersion(0);
        return a;
    }

    private static List<String> titles(ArticleBatchRepository repo) {
        return repo.findAll().map(Article::getTitle).sorted().toList();
    }

    @ParameterizedTest
    @MethodSource("repositories")
    void insertsSeveralEntities(ArticleBatchRepository repo) {
        List<Article> created = repo.createAll(List.of(article("a"), article("b")));
        Article[] array = repo.createArray(new Article[]{article("c")});
        repo.createQuietly(List.of(article("d")));

        assertThat(created).extracting(Article::getId).doesNotContainNull();
        assertThat(array).singleElement().extracting(Article::getId).isNotNull();
        assertThat(titles(repo)).containsExactly("a", "b", "c", "d");
    }

    @ParameterizedTest
    @MethodSource("repositories")
    void updatesSavesAndDeletesSeveralEntities(ArticleBatchRepository repo) {
        List<Article> created = repo.createAll(List.of(article("a"), article("b"), article("c")));
        created.forEach(a -> a.setTitle(a.getTitle().toUpperCase()));

        assertThat(repo.modifyAll(created.subList(0, 2))).extracting(Article::getVersion).containsExactly(1, 1);
        assertThat(repo.storeAll(List.of(created.get(2), article("d")))).hasSize(2);
        assertThat(titles(repo)).containsExactly("A", "B", "C", "d");

        repo.removeAll(created.subList(0, 2));
        assertThat(titles(repo)).containsExactly("C", "d");
    }

    static Stream<Named<ArticleCrudRepository>> crudRepositories() {
        return Stream.of(
                Named.of("annotation processor", generatedData.repository(ArticleCrudRepository.class)),
                Named.of("runtime proxy", runtimeData.runtimeRepository(ArticleCrudRepository.class)));
    }

    /** MANSART-017: the methods {@code CrudRepository} adds to {@code BasicRepository}. */
    @ParameterizedTest
    @MethodSource("crudRepositories")
    void crudRepositoryInsertsAndUpdates(ArticleCrudRepository repo) {
        Article one = repo.insert(article("one"));
        List<Article> more = repo.insertAll(List.of(article("two"), article("three")));
        assertThat(one.getId()).isNotNull();
        assertThat(more).extracting(Article::getId).doesNotContainNull();

        one.setTitle("ONE");
        assertThat(repo.update(one).getVersion()).isEqualTo(1);
        more.forEach(a -> a.setTitle(a.getTitle().toUpperCase()));
        assertThat(repo.updateAll(more)).extracting(Article::getVersion).containsExactly(1, 1);
        assertThat(repo.findAll().map(Article::getTitle).sorted()).containsExactly("ONE", "THREE", "TWO");

        Article stale = article("stale");
        stale.setId(one.getId());
        assertThatThrownBy(() -> repo.update(stale)).isInstanceOf(OptimisticLockingFailureException.class);
    }
}
