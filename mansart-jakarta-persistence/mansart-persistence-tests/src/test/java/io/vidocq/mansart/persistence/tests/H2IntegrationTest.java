    @Test
    void mergeUpdatesEntity() {
        // Given
        io.vidocq.mansart.persistence.tests.model.SimpleAssignedIdEntity entity = 
                new io.vidocq.mansart.persistence.tests.model.SimpleAssignedIdEntity();
        entity.setId(200L);
        entity.setName("Original Name");
        entity.setValue(Integer.valueOf(1));

        EntityTransaction tx = em.getTransaction();
        tx.begin();
        em.persist(entity);
        em.flush();
        tx.commit();

        // When - detach and change
        em.detach(entity);
        entity.setName("Updated Name");
        entity.setValue(Integer.valueOf(999));

        tx = em.getTransaction();
        tx.begin();
        em.merge(entity);
        em.flush();
        tx.commit();

        // Then
        EntityTransaction tx2 = em.getTransaction();
        tx2.begin();
        io.vidocq.mansart.persistence.tests.model.SimpleAssignedIdEntity found = 
                em.find(io.vidocq.mansart.persistence.tests.model.SimpleAssignedIdEntity.class, 200L);
        tx2.commit();

        assertThat(found).isNotNull();
        assertThat(found.getName()).isEqualTo("Updated Name");
        assertThat(found.getValue()).isEqualTo(999);
    }

