    @Test
    void versionedEntityIncrementsVersionOnUpdate() {
        // Given
        io.vidocq.mansart.persistence.tests.model.VersionedEntity entity = 
                new io.vidocq.mansart.persistence.tests.model.VersionedEntity();
        entity.setId(400L);
        entity.setName("Version 0");

        EntityTransaction tx = em.getTransaction();
        tx.begin();
        em.persist(entity);
        em.flush();
        tx.commit();

        int initialVersion = entity.getVersion();
        assertThat(initialVersion).isZero();

        // When - update
        entity.setName("Version 1");
        tx = em.getTransaction();
        tx.begin();
        em.merge(entity);
        em.flush();
        tx.commit();

        // Then
        EntityTransaction tx2 = em.getTransaction();
        tx2.begin();
        io.vidocq.mansart.persistence.tests.model.VersionedEntity found = 
                em.find(io.vidocq.mansart.persistence.tests.model.VersionedEntity.class, 400L);
        tx2.commit();

        assertThat(found).isNotNull();
        assertThat(found.getVersion()).isEqualTo(initialVersion + 1);
        assertThat(found.getName()).isEqualTo("Version 1");
    }
