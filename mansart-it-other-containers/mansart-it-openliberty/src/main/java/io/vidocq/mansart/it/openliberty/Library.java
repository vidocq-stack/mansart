package io.vidocq.mansart.it.openliberty;

import jakarta.annotation.Resource;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.context.Initialized;
import jakarta.enterprise.event.Observes;
import jakarta.inject.Inject;
import jakarta.transaction.Transactional;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

/** Writes through the repository inside Liberty's transactions; creates the table at start-up. */
@ApplicationScoped
public class Library {

    @Inject
    Books books;

    @Resource(lookup = "java:comp/DefaultDataSource")
    DataSource dataSource;

    void createTable(@Observes @Initialized(ApplicationScoped.class) Object started) throws SQLException {
        try (Connection c = dataSource.getConnection(); Statement s = c.createStatement()) {
            s.execute("CREATE TABLE IF NOT EXISTS \"books\" ("
                    + "  \"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + "  \"title\" VARCHAR(200) NOT NULL)");
        }
    }

    @Transactional
    public void add(String title) {
        books.save(book(title));
    }

    @Transactional
    public void addThenFail(String title) {
        books.save(book(title));
        throw new IllegalStateException("the book saved above must be rolled back");
    }

    public long count(String title) {
        return books.countByTitle(title);
    }

    private static Book book(String title) {
        Book b = new Book();
        b.setTitle(title);
        return b;
    }
}
