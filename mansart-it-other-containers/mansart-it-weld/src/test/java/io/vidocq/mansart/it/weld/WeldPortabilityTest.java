package io.vidocq.mansart.it.weld;

import jakarta.transaction.TransactionManager;
import org.jboss.weld.environment.se.Weld;
import org.jboss.weld.environment.se.WeldContainer;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.Statement;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The Mansart jars, unchanged, under Weld SE on a class path (vidocq-workspace#15, mansart#35):
 * Mansart Data's build compatible extension registers the repository whose implementation the
 * processor generated, Mansart Transactions publishes its transaction manager and binds its
 * {@code @Transactional} interceptor, and a rollback undoes the repository's writes. Nothing
 * generated for Vauban is used.
 */
class WeldPortabilityTest {

    private static WeldContainer container;

    @BeforeAll
    static void start() throws Exception {
        try (Connection c = H2Store.h2().getConnection(); Statement s = c.createStatement()) {
            s.execute("CREATE TABLE IF NOT EXISTS \"books\" ("
                    + "  \"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + "  \"title\" VARCHAR(200) NOT NULL)");
        }
        container = new Weld().initialize();
    }

    @AfterAll
    static void stop() {
        if (container != null) {
            container.close();
        }
    }

    @BeforeEach
    void emptyTable() throws Exception {
        try (Connection c = H2Store.h2().getConnection(); Statement s = c.createStatement()) {
            s.execute("DELETE FROM \"books\"");
        }
    }

    @Test
    void vaubanIsNotOnTheClassPath() {
        assertThrows(ClassNotFoundException.class,
                () -> Class.forName("io.vidocq.vauban.core.container.VaubanContainer"));
    }

    @Test
    void theRepositoryIsInjectedAndQueries() {
        Books books = container.select(Books.class).get();
        Book saved = new Book();
        saved.setTitle("Les Misérables");
        books.save(saved);

        assertEquals(1, books.findByTitle("Les Misérables").size());
        assertEquals(1L, books.countByTitle("Les Misérables"));
    }

    @Test
    void theTransactionManagerIsPublished() {
        assertTrue(container.select(TransactionManager.class).isResolvable());
    }

    @Test
    void aTransactionalMethodCommitsItsWrites() throws Exception {
        container.select(Library.class).get().addBoth("Germinal", "Nana");

        assertEquals(2, countRows());
    }

    @Test
    void aTransactionalMethodRollsItsWritesBack() throws Exception {
        Library library = container.select(Library.class).get();

        assertThrows(IllegalStateException.class, () -> library.addThenFail("Doomed"));

        assertEquals(0, countRows(), "@Transactional must undo the repository write");
    }

    /** Rows as seen by an independent connection, never the transaction's own view. */
    private static int countRows() throws Exception {
        try (Connection c = H2Store.h2().getConnection(); Statement s = c.createStatement();
             ResultSet rs = s.executeQuery("SELECT COUNT(*) FROM \"books\"")) {
            rs.next();
            return rs.getInt(1);
        }
    }
}
